import { Router } from 'express';
import { authenticate, requireTipo } from '../../middlewares/auth.js';
import { requirePermiso } from '../../middlewares/permisos.js';
import { validate } from '../../middlewares/validate.js';
import { asyncHandler } from '../../utils/asyncHandler.js';
import * as controller from './rrhh.controller.js';
import { empleadoSchema, puestoSchema } from './rrhh.schemas.js';
import { periodoSchema } from './planilla.schemas.js';
import * as planilla from './planilla.controller.js';

const router = Router();
router.use(authenticate, requireTipo('admin'));
const gestionar = requirePermiso('RRHH_GESTIONAR_EMPLEADOS');
router.get('/puestos', gestionar, asyncHandler(controller.listarPuestos));
router.post('/puestos', gestionar, validate(puestoSchema), asyncHandler(controller.crearPuesto));
router.put('/puestos/:id', gestionar, validate(puestoSchema), asyncHandler(controller.actualizarPuesto));
router.delete('/puestos/:id', gestionar, asyncHandler(controller.desactivarPuesto));
router.patch('/puestos/:id/activar', gestionar, asyncHandler(controller.activarPuesto));
router.get('/empleados', gestionar, asyncHandler(controller.listarEmpleados));
router.post('/empleados', gestionar, validate(empleadoSchema), asyncHandler(controller.crearEmpleado));
router.put('/empleados/:id', gestionar, validate(empleadoSchema), asyncHandler(controller.actualizarEmpleado));
router.delete('/empleados/:id', gestionar, asyncHandler(controller.desactivarEmpleado));
router.patch('/empleados/:id/activar', gestionar, asyncHandler(controller.activarEmpleado));
router.get('/planillas', requirePermiso('RRHH_VER_PLANILLA'), asyncHandler(planilla.listar));
router.post('/planillas', requirePermiso('RRHH_CALCULAR_PLANILLA'), validate(periodoSchema), asyncHandler(planilla.crear));
router.post('/planillas/:id/calculo', requirePermiso('RRHH_CALCULAR_PLANILLA'), asyncHandler(planilla.calcular));
router.post('/planillas/:id/procesamiento', requirePermiso('RRHH_CALCULAR_PLANILLA'), asyncHandler(planilla.procesar));
router.get('/planillas/:id', requirePermiso('RRHH_VER_PLANILLA'), asyncHandler(planilla.obtener));
router.get('/planillas/:id/pdf', requirePermiso('RRHH_VER_PLANILLA'), asyncHandler(planilla.pdfPlanilla));
router.get('/planillas/:id/empleados/:idEmpleado/boleta.pdf', requirePermiso('RRHH_VER_PLANILLA'), asyncHandler(planilla.pdfBoleta));
export default router;
